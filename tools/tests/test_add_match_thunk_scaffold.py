"""Only proven generator-owned gap thunks yield to the ordinary byte gate."""
import sys
from pathlib import Path
from types import SimpleNamespace

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import add_match
import build
from test_add_match_import_scaffold import admission, landing


@pytest.fixture
def gap_thunk_landing(landing, monkeypatch):
    row, _, ledger, write_row, calls = landing
    row.update(name="?j_00001000@@YAXXZ", source="Code/gen_small/gthunks_009_admitted.cpp",
               target_size="5", notes="gen-thunk;gap;target=0x00002000")
    source = ledger.parent.parent / row["source"]
    source.parent.mkdir(parents=True, exist_ok=True)
    source.write_text(
        "// Generated by: python3 tools/gen_small.py gen-gap-thunks --batch 9 --limit 500\n"
        "// Do not edit by hand; regenerate instead.\n\n"
        "void b_00002000();\nvoid j_00001000() { b_00002000(); }\n", encoding="utf-8")
    monkeypatch.setattr(build, "read_target_bytes", lambda rva, size: bytes.fromhex("e9fb0f0000"))
    write_row(row)
    return row, source, ledger, write_row, calls


def test_gap_thunk_replacement_runs_normal_build(gap_thunk_landing, admission):
    row, _, ledger, _, calls = gap_thunk_landing
    admission()
    assert len(calls) == 1
    assert row["name"] not in ledger.read_text()


def test_failed_gap_thunk_replacement_restores_row(gap_thunk_landing, admission, monkeypatch):
    _, _, ledger, _, _ = gap_thunk_landing
    before = ledger.read_bytes()
    monkeypatch.setattr(add_match.subprocess, "run", lambda *args, **kwargs: SimpleNamespace(returncode=1))
    with pytest.raises(SystemExit):
        admission()
    assert ledger.read_bytes() == before


def test_backward_gap_thunk_replacement(gap_thunk_landing, admission, monkeypatch):
    row, source, _, write_row, calls = gap_thunk_landing
    row["notes"] = "gen-thunk;gap;target=0x00000800"
    source.write_text(source.read_text().replace("b_00002000", "b_00000800"))
    monkeypatch.setattr(build, "read_target_bytes", lambda rva, size: bytes.fromhex("e9fbf7ffff"))
    write_row(row)
    admission()
    assert len(calls) == 1


def test_gap_thunk_replacement_can_recover_the_complete_entry(gap_thunk_landing, admission, monkeypatch):
    row, _, ledger, _, calls = gap_thunk_landing
    if admission is add_match.main:
        arguments = list(sys.argv)
        arguments[2:4] = ["0x00000FFA", "11"]
        monkeypatch.setattr(sys, "argv", arguments)
    else:
        (ledger.parent.parent / "rows.csv").write_text(
            "_D3DXMatrixMultiply@12,0x00000FFA,11,Code/masm_dumps/Import.asm,,0x00001000\n")
    admission()
    assert len(calls) == 1
    assert row["name"] not in ledger.read_text()
    assert ",0x00000FFA,11," in ledger.read_text()


@pytest.mark.parametrize("forge", ["real-name", "rva-name", "source", "path-traversal", "marker",
                                   "batch", "missing-source", "extra-code", "callee", "declaration",
                                   "duplicate", "duplicate-callee", "notes-suffix", "notes-target", "size",
                                   "status", "bytes", "bytes-target", "short-bytes", "read-error"])
def test_unproven_gap_thunk_never_retires_claim(gap_thunk_landing, admission, monkeypatch, forge):
    row, source, ledger, write_row, calls = gap_thunk_landing
    if forge == "real-name":
        row["name"] = "?existing@@YAXXZ"
    elif forge == "rva-name":
        row["name"] = "?j_00001001@@YAXXZ"
    elif forge == "source":
        row["source"] = "Code/RealOwner.cpp"
    elif forge == "path-traversal":
        row["source"] = "Code/gen_small/../gen_small/gthunks_009_admitted.cpp"
    elif forge == "marker":
        source.write_text(source.read_text().replace("Generated by:", "Copied from:"))
    elif forge == "batch":
        source.write_text(source.read_text().replace("--batch 9", "--batch 8"))
    elif forge == "missing-source":
        source.unlink()
    elif forge == "extra-code":
        source.write_text(source.read_text() + "int unrelated = 1;\n")
    elif forge == "callee":
        source.write_text(source.read_text().replace("{ b_00002000(); }", "{ b_00002001(); }"))
    elif forge == "declaration":
        source.write_text(source.read_text().replace("void b_00002000();\n", ""))
    elif forge == "duplicate":
        source.write_text(source.read_text() + "void j_00001000() { b_00002000(); }\n")
    elif forge == "duplicate-callee":
        source.write_text(source.read_text() + "void j_00001000() { b_00002001(); }\n")
    elif forge == "notes-suffix":
        row["notes"] += ";parent=RealOwner"
    elif forge == "notes-target":
        row["notes"] = "gen-thunk;gap;target=0x00002001"
    elif forge == "size":
        row["target_size"] = "6"
    elif forge == "status":
        row["status"] = "pending"
    elif forge == "bytes-target":
        monkeypatch.setattr(build, "read_target_bytes", lambda rva, size: bytes.fromhex("e9fc0f0000"))
    elif forge == "short-bytes":
        monkeypatch.setattr(build, "read_target_bytes", lambda rva, size: bytes.fromhex("e9fb0f00"))
    elif forge == "read-error":
        def unavailable(rva, size):
            raise ValueError("unmapped retail bytes")
        monkeypatch.setattr(build, "read_target_bytes", unavailable)
    else:
        monkeypatch.setattr(build, "read_target_bytes", lambda rva, size: b"\x90" * size)
    write_row(row)
    before = ledger.read_bytes()
    with pytest.raises(SystemExit):
        admission()
    assert ledger.read_bytes() == before
    assert not calls
